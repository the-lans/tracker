"""Калькулятор для ручного E2E-тестирования трекера (docs/qa_e2e_manual.md)."""


def add(left: float, right: float) -> float:
    return left + right


def subtract(left: float, right: float) -> float:
    return left - right


def multiply(left: float, right: float) -> float:
    return left * right
